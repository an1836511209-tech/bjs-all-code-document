const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({channel:'chrome',headless:true});
 try {
  const page = await browser.newPage({viewport:{width:1500,height:1100}});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8024/console/');
  await page.locator('#institutionWorkbook:not(:disabled)').waitFor();
  assert.equal(await page.locator('#institutionWorkbook').isChecked(),false);
  await page.locator('#institutionWorkbook').check();
  await page.locator('#input').fill('开启附件的一页纸BP');
  await page.locator('#sendBtn').click();
  await page.locator('#runStatus').filter({hasText:'已完成'}).waitFor();
  const wordTitle=await page.locator('#previewTitle').textContent();
  assert(wordTitle.includes('开启附件'));
  let saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('bjs-console-v2')));
  const first=saved.workspaces.flatMap(w=>w.conversations).find(c=>c.taskId);
  const word=await (await page.request.get(`http://127.0.0.1:8024/api/tasks/${first.taskId}/state`)).json();
  assert.equal(word.artifacts.length,1);
  await page.locator('#convoFilesBody').getByText('投资机构匹配.xlsx',{exact:true}).waitFor();
  assert.equal(await page.locator('#previewTitle').textContent(),wordTitle);
  await page.locator('#artifactTabs').getByRole('tab',{name:'投资机构匹配.xlsx'}).click();
  await page.locator('#paper th').filter({hasText:'匹配标签数（接口）'}).waitFor();
  assert.equal(await page.locator('#paper th').count(),4);
  assert((await page.locator('#paper').textContent()).includes('速冻食品制造'));
  const url=await page.locator('#paper a').getAttribute('href');
  const download=await page.request.get(url);
  assert.equal(download.status(),200);
  assert.equal(download.headers()['content-type'],'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet');
  assert.equal((await download.body()).subarray(0,2).toString(),'PK');
  await page.reload();
  await page.locator('#convoFilesBody').getByText('投资机构匹配.xlsx',{exact:true}).waitFor();
  assert.equal(await page.locator('#institutionWorkbook').isChecked(),true);
  await page.locator('#convoFilesBody').getByText('投资机构匹配.xlsx',{exact:true}).click();
  await page.locator('#paper th').first().waitFor();
  await page.screenshot({path:'.runtime/diagnostics/institution-workbook-preview.png',fullPage:true});
  await page.locator('[data-add="ws-default"]').click();
  assert.equal(await page.locator('#institutionWorkbook').isChecked(),false);
  await page.locator('#input').fill('不开启附件的一页纸BP');
  await page.locator('#sendBtn').click();
  await page.locator('#runStatus').filter({hasText:'已完成'}).waitFor();
  await page.waitForTimeout(2500);
  assert.equal(await page.locator('#convoFilesBody').getByText('投资机构匹配.xlsx',{exact:true}).count(),0);
  const stats=await (await page.request.get('http://127.0.0.1:8024/qa/stats')).json();
  assert.equal(stats.calls.length,1);
  await page.locator('[data-add="ws-default"]').click();
  await page.locator('#institutionWorkbook').check();
  await page.locator('#input').fill('附件失败的一页纸BP');
  await page.locator('#sendBtn').click();
  await page.locator('#runStatus').filter({hasText:'已完成'}).waitFor();
  await page.locator('#workbookStatus').filter({hasText:'生成失败'}).waitFor();
  assert.equal(await page.locator('#runStatus').textContent(),'已完成');
  assert((await page.locator('#previewTitle').textContent()).includes('附件失败'));
  assert.equal(await page.locator('#convoFilesBody').getByText('投资机构匹配.xlsx',{exact:true}).count(),0);
  // Simulate an HTTP deployment where randomUUID is unavailable.
  await page.evaluate(() => Object.defineProperty(globalThis.crypto, 'randomUUID', {value:undefined, configurable:true}));
  await page.getByRole('button',{name:'更新标签后重试',exact:true}).click();
  await page.locator('#workbookStatus').filter({hasText:'请手动选择标签'}).waitFor();
  await page.locator('#workbookStatus details summary').click();
  await page.locator('#workbookStatus input[value="互联网零售"]').check();
  await page.getByRole('button',{name:'使用所选标签重试',exact:true}).click();
  await page.locator('#workbookStatus').filter({hasText:'已生成'}).waitFor();
  assert.equal(await page.locator('#runStatus').textContent(),'已完成');
  const retryStats=await (await page.request.get('http://127.0.0.1:8024/qa/stats')).json();
  assert.deepEqual(retryStats.requests.at(-1),{name:'export_matched_institutions',arguments:{track_tags:['互联网零售']}});
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({passed:true,wordDeliveredFirst:true,offMadeNoExport:true,failureIsolated:true,refreshedManualRetry:true,withoutRandomUUID:true,browserErrors:errors}));
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
