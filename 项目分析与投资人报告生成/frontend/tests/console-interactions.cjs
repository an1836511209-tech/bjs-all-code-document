const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({channel:'chrome',headless:true});
 try {
  const page = await browser.newPage({viewport:{width:1440,height:1100}});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8017/console/');
  const initialList=await (await page.request.get('http://127.0.0.1:8017/api/conversations')).json();
  await page.locator('[data-add="ws-default"]').click();
  await page.locator('#input').fill('帮我生成一页纸BP');
  await page.locator('#sendBtn').click();
  await page.locator('.approval-q').filter({hasText:'业务类型'}).waitFor();
  assert.equal(await page.getByText('确认无误，可执行',{exact:true}).count(),0);
  await page.locator('.approval-opt').filter({hasText:'增资扩股'}).click();
  await page.locator('.approval textarea').fill('请保留现有团队，融资金额为2000万元');
  await page.screenshot({path:'.runtime/diagnostics/bp-question-business.png',fullPage:true});
  await page.locator('.approval-send').click();
  await page.locator('.approval-q').filter({hasText:'北交互联'}).waitFor();
  let stored = await page.evaluate(()=>JSON.parse(localStorage.getItem('bjs-console-v2')));
  let conv=stored.workspaces.flatMap(w=>w.conversations).find(c=>c.taskId);
  const taskId=conv.taskId;
  assert.equal(conv.activeSkill,'one-pager');
  await page.locator('.approval-opt').filter({hasText:'不确定'}).click();
  await page.locator('.approval textarea').fill('财务数字以我上传的材料为准');
  await page.reload();
  await page.locator('.approval-q').filter({hasText:'北交互联'}).waitFor();
  assert.equal(await page.locator('.approval-opt').count(),3);
  assert.equal(await page.locator('.approval textarea').inputValue(),'财务数字以我上传的材料为准');
  assert.equal(await page.locator('.approval-opt.selected').count(),1);
  await page.locator('.approval-opt').filter({hasText:'不确定'}).click();
  await page.locator('.approval textarea').fill('财务数字以我上传的材料为准');
  await page.screenshot({path:'.runtime/diagnostics/bp-question-disclosure.png',fullPage:true});
  await page.locator('.approval-send').click();
  await page.locator('#runStatus').filter({hasText:'已完成'}).waitFor();
  await page.locator('#input').fill('追加说明：请突出国产替代优势');
  await page.locator('#sendBtn').click();
  await page.locator('#runStatus').filter({hasText:'已完成'}).waitFor();
  const snapshot=await (await page.request.get(`http://127.0.0.1:8017/api/tasks/${taskId}/state`)).json();
  assert.equal(snapshot.turns.filter(t=>t.role==='user').length,4);
  assert(snapshot.turns.some(t=>t.text.includes('请保留现有团队')));
  assert(snapshot.turns.some(t=>t.text.includes('财务数字以我上传的材料为准')));
  const list=await (await page.request.get('http://127.0.0.1:8017/api/conversations')).json();
  assert.equal(list.items.length,initialList.items.length+1);
  await page.reload();
  await page.locator('#convoFilesBody').getByText('交互测试.docx',{exact:true}).waitFor();
  assert.deepEqual(errors,[]);
  assert(snapshot.turns.some(t=>t.text.includes('追加说明：请突出国产替代优势')));
  const downloaded=await page.request.get(`http://127.0.0.1:8017/api/artifacts/${'artifact_'+'a'.repeat(32)}/content`);
  assert.equal(downloaded.status(),200);
  // B's SSE arrives while A's submission is still awaiting its response.
  await page.route('**/api/dev/runs',async route=>{
    if ((route.request().postData()||'').includes('慢提交A')) await new Promise(resolve=>setTimeout(resolve,800));
    await route.continue();
  });
  await page.locator('[data-add="ws-default"]').click();
  await page.locator('#skillSelect').selectOption('one-pager');
  const uniqueA = `慢提交A${Date.now().toString().slice(-6)}`;
  await page.locator('#input').fill(`${uniqueA} 一页纸`);
  await page.locator('#sendBtn').click();
  await page.locator('[data-add="ws-default"]').click();
  assert.equal(await page.locator('#skillSelect').inputValue(),'');
  await page.locator('#input').fill('并发B 一页纸');
  await page.locator('#sendBtn').click();
  await page.locator('.approval-q').filter({hasText:'业务类型'}).waitFor();
  await page.locator('.convo').filter({hasText:uniqueA}).click();
  await page.locator('.approval-q').filter({hasText:'业务类型'}).waitFor();
  assert.equal(await page.locator('#skillSelect').inputValue(),'one-pager');
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({passed:true,taskId,userTurns:4,browserErrors:errors,screenshots:['bp-question-business.png','bp-question-disclosure.png']}));
 } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
